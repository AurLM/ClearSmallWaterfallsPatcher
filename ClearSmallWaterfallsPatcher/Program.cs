            Log($"generated {meshCache.Count} meshes and {tintGroups.Count * 2} textures in {outDir}");
        }

        static void Replace(byte[] buf, string from, string to)
        {
            var a = Encoding.ASCII.GetBytes(from); var b = Encoding.ASCII.GetBytes(to);
            if (a.Length != b.Length) throw new InvalidOperationException("replacement must keep the same length");
            for (int i = 0; i + a.Length <= buf.Length; i++)
            {
                int j = 0;
                while (j < a.Length && char.ToLowerInvariant((char)buf[i + j]) == (char)a[j]) j++;
                if (j == a.Length) { Array.Copy(b, 0, buf, i, b.Length); i += a.Length - 1; }
            }
        }
    }

    /// <summary>Uncompressed 32-bit BGRA DDS with a full mip chain (same format as the main mod's textures).</summary>
    static class Dds
    {
        public static byte[] ReadTopAlpha(string path, out int w, out int h)
        {
            var b = File.ReadAllBytes(path);
            h = BitConverter.ToInt32(b, 12); w = BitConverter.ToInt32(b, 16);
            var a = new byte[w * h];
            for (int i = 0; i < w * h; i++) a[i] = b[128 + i * 4 + 3];
            return a;
        }

        static void Header(BinaryWriter o, int w, int h, int mips)
        {
            o.Write(Encoding.ASCII.GetBytes("DDS "));
            o.Write(124); o.Write(0x1 | 0x2 | 0x4 | 0x8 | 0x1000 | 0x20000); o.Write(h); o.Write(w); o.Write(w * 4); o.Write(0); o.Write(mips);
            o.Write(new byte[44]);
            o.Write(32); o.Write(0x41); o.Write(0); o.Write(32);
            o.Write(0x00FF0000); o.Write(0x0000FF00); o.Write(0x000000FF); unchecked { o.Write((int)0xFF000000); }
            o.Write(0x1000 | 0x8 | 0x400000); o.Write(0); o.Write(0); o.Write(0); o.Write(0);
        }

        public static void WriteFlat(string path, byte r, byte g, byte b, int size)
        {
            var alpha = Enumerable.Repeat((byte)255, size * size).ToArray();
            WriteWithAlpha(path, r, g, b, alpha, size, size);
        }

        public static void WriteWithAlpha(string path, byte r, byte g, byte b, byte[] alpha, int w, int h)
        {
            var levels = new List<(byte[] A, int W, int H)> { (alpha, w, h) };
            while (Math.Min(levels[^1].W, levels[^1].H) > 1)
            {
                var (pa, pw, ph) = levels[^1];
                int nw = Math.Max(1, pw / 2), nh = Math.Max(1, ph / 2);
                var na = new byte[nw * nh];
                for (int y = 0; y < nh; y++)
                    for (int x = 0; x < nw; x++)
                    {
                        int s = 0, n = 0;
                        for (int dy = 0; dy < 2; dy++) for (int dx = 0; dx < 2; dx++)
                        {
                            int sx = Math.Min(pw - 1, x * 2 + dx), sy = Math.Min(ph - 1, y * 2 + dy);
                            s += pa[sy * pw + sx]; n++;
                        }
                        na[y * nw + x] = (byte)(s / n);
                    }
                levels.Add((na, nw, nh));
            }
            using var o = new BinaryWriter(File.Create(path));
            Header(o, w, h, levels.Count);
            foreach (var (a, lw, lh) in levels)
                for (int i = 0; i < lw * lh; i++) { o.Write(b); o.Write(g); o.Write(r); o.Write(a[i]); }
        }
    }
