// Clear Small Waterfalls - Synthesis patcher
// Reads the user's FINAL load order (water mods, tweaks, lighting patches, mod-added drains...) and:
//   - tints every small stream with the colour of the water it actually falls into
//   - fits each stream's length to its own floor / water surface
//   - under small drains only: softens splashes, removes heavy churn, turns foam rings on water into
//     clear ripples, recentres splashes on the stream. Cascades are never touched.
// It ignores ClearSmallWaterfalls.esp (the standalone plugin) and replaces everything it did.
// Tinted copies of the shipped base meshes and their textures are written next to the output plugin.

