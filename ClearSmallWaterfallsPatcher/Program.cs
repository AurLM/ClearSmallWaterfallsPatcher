                        ctx.GetOrAddAsOverride(state.PatchMod); restored++; break;
                    }
                }
            }

            Log($"streams: {refs.Values.Count(r => r.Kind == Kind.Drain)}, soft splashes: {toSoft.Count}, ripples: {ripple.Count}, " +
