    {
        static Lazy<Settings> _settings = null!;

        static readonly string LogPath = Path.Combine(AppContext.BaseDirectory, "ClearSmallWaterfalls_log.txt");

        static void Log(string msg)
        {
            var line = $"[CSW] {msg}";
            Console.WriteLine(line);
            try { File.AppendAllText(LogPath, DateTime.Now.ToString("HH:mm:ss") + " " + line + Environment.NewLine); } catch { }
        }

        public static async Task<int> Main(string[] args)
        {
            try { File.WriteAllText(LogPath, $"Clear Small Waterfalls patcher log - {DateTime.Now}{Environment.NewLine}args: {string.Join(" ", args)}{Environment.NewLine}"); } catch { }
            try
            {
                var code = await SynthesisPipeline.Instance
                    .AddPatch<ISkyrimMod, ISkyrimModGetter>(RunPatch)
                    .SetAutogeneratedSettings("Settings", "settings.json", out _settings)
                    .SetTypicalOpen(GameRelease.SkyrimSE, "ClearSmallWaterfallsPatch.esp")
                    .Run(args);
                Log($"exit code {code}");
                return code;
            }
            catch (Exception e)
            {
                Log("FATAL " + e);
                return 1;
            }
        }

        // ------------------------------------------------------------------ data
        class DrainInfo
        {
            public string Model = "";
            public double DefaultLen;
            public List<int> Buckets = new();
            public double LandX, LandY;
        }

        class Data
        {
            public Dictionary<FormKey, DrainInfo> Drains = new();
            public HashSet<string> BigFoam = new(), SmallSplash = new(), ImpactMarkers = new(), WaterRing = new();
            public List<string> BigFalls = new();
            public Dictionary<string, string> SoftSplash = new();       // vanilla splash model -> soft mesh
            public double Radius, MoveMax, Step, Sink, BigDrop, WaterSearch, Merge;
            public Dictionary<FormKey, (string Mesh, double LandingShift)> Barrels = new();
            public HashSet<FormKey> Hide = new();
            public double[] NeutralVanilla = { 58, 60, 60 }, NeutralEnb = { 22, 24, 25 };
        }

        enum Kind { Drain, Big, Small, Marker, Fall, Water }

        class Ref
        {
            public FormKey Key;
            public Kind Kind;
            public string Model = "";
            public FormKey Base;
            public double[] Pos = new double[3];
            public double[] Rot = new double[3];
            public double Scale = 1.0;
            public FormKey Space;            // worldspace (exterior) or cell (interior)
            public bool Exterior;
            public FormKey Cell;
            public FormKey? WaterType;       // for placed water activators
            public IModContext<ISkyrimMod, ISkyrimModGetter, IPlacedObject, IPlacedObjectGetter> Ctx = null!;
        }

        static FormKey ParseKey(string s)
        {
            // "Skyrim.esm:1033F3"
            var i = s.LastIndexOf(':');
            return new FormKey(ModKey.FromNameAndExtension(s.Substring(0, i)), uint.Parse(s.Substring(i + 1), NumberStyles.HexNumber));
        }

        static Data LoadData(string path)
        {
            if (!File.Exists(path))
                throw new FileNotFoundException(
                    "Clear Small Waterfalls patcher data not found. Install the main mod (ENB or CS version) and run Synthesis through your mod manager. Missing: " + path);
            using var doc = JsonDocument.Parse(File.ReadAllText(path));
            var r = doc.RootElement;
            var d = new Data();
            foreach (var p in r.GetProperty("drains").EnumerateObject())
            {
                var v = p.Value;
                var info = new DrainInfo
                {
                    Model = v.GetProperty("model").GetString()!,
                    DefaultLen = v.GetProperty("default_len").GetDouble(),
                    Buckets = v.GetProperty("buckets").EnumerateArray().Select(x => x.GetInt32()).ToList(),
                    LandX = v.GetProperty("landing")[0].GetDouble(),
                    LandY = v.GetProperty("landing")[1].GetDouble(),
                };
                d.Drains[ParseKey(p.Name)] = info;
            }
            HashSet<string> Set(string n) => r.GetProperty(n).EnumerateArray().Select(x => x.GetString()!.ToLowerInvariant()).ToHashSet();
            d.BigFoam = Set("big_foam");
            d.SmallSplash = Set("small_splash");
            d.ImpactMarkers = Set("impact_markers");
            d.WaterRing = Set("water_ring");
            d.BigFalls = r.GetProperty("big_falls").EnumerateArray().Select(x => x.GetString()!.ToLowerInvariant()).ToList();
            foreach (var p in r.GetProperty("soft_splash").EnumerateObject()) d.SoftSplash[p.Name.ToLowerInvariant()] = p.Value.GetString()!;
            d.Radius = r.GetProperty("radius").GetDouble();
            d.MoveMax = r.GetProperty("move_max").GetDouble();
            d.Step = r.GetProperty("step").GetDouble();
            d.Sink = r.GetProperty("sink").GetDouble();
            d.BigDrop = r.GetProperty("big_drop").GetDouble();
            d.WaterSearch = r.GetProperty("water_search").GetDouble();
            d.Merge = r.GetProperty("merge").GetDouble();
            foreach (var p in r.GetProperty("specials").EnumerateObject())
                if (p.Value.GetProperty("kind").GetString() == "barrel")
                    d.Barrels[ParseKey(p.Name)] = (p.Value.GetProperty("mesh").GetString()!, p.Value.GetProperty("landing_shift").GetDouble());
            foreach (var h in r.GetProperty("hide").EnumerateArray()) d.Hide.Add(ParseKey(h.GetString()!));
            var neu = r.GetProperty("neutral");
            d.NeutralVanilla = neu.GetProperty("vanilla").EnumerateArray().Select(x => x.GetDouble()).ToArray();
            d.NeutralEnb = neu.GetProperty("enb").EnumerateArray().Select(x => x.GetDouble()).ToArray();
            return d;
        }

        // ------------------------------------------------------------------ maths
        static double[,] Rot(double rx, double ry, double rz)
        {
            // Skyrim REFR rotation (radians, clockwise): R = Rx(-rx) * Ry(-ry) * Rz(-rz)
            double[,] Rx(double a) { var c = Math.Cos(a); var s = Math.Sin(a); return new double[,] { { 1, 0, 0 }, { 0, c, -s }, { 0, s, c } }; }
            double[,] Ry(double a) { var c = Math.Cos(a); var s = Math.Sin(a); return new double[,] { { c, 0, s }, { 0, 1, 0 }, { -s, 0, c } }; }
            double[,] Rz(double a) { var c = Math.Cos(a); var s = Math.Sin(a); return new double[,] { { c, -s, 0 }, { s, c, 0 }, { 0, 0, 1 } }; }
            return Mul(Mul(Rx(-rx), Ry(-ry)), Rz(-rz));
        }

        static double[,] Mul(double[,] a, double[,] b)
        {
            var o = new double[3, 3];
            for (int i = 0; i < 3; i++) for (int j = 0; j < 3; j++) for (int k = 0; k < 3; k++) o[i, j] += a[i, k] * b[k, j];
            return o;
        }

        static double[] Apply(double[,] m, double[] v) => new[]
        {
            m[0, 0] * v[0] + m[0, 1] * v[1] + m[0, 2] * v[2],
            m[1, 0] * v[0] + m[1, 1] * v[1] + m[1, 2] * v[2],
            m[2, 0] * v[0] + m[2, 1] * v[1] + m[2, 2] * v[2],
        };

        static double H(double[] a, double[] b) => Math.Sqrt((a[0] - b[0]) * (a[0] - b[0]) + (a[1] - b[1]) * (a[1] - b[1]));

        static double[] Tint(System.Drawing.Color sh, System.Drawing.Color dp, bool enb)
        {
            if (enb)
            {
                // ENB renders water mostly through reflections and its own water settings, so the plugin colour
                // barely shows (e.g. a "brown" water type looks blue under the sky). Keep only a faint hint of the
                // water's hue and let the stream's own ENB reflections do the rest, like the water does.
                var c = new[] { 0.5 * sh.R + 0.5 * dp.R, 0.5 * sh.G + 0.5 * dp.G, 0.5 * sh.B + 0.5 * dp.B };
                var m = c.Average();
                if (m < 1) return Array.Empty<double>();
                c = c.Select(x => x / m * 50).ToArray();
                var g = c.Average();
                return c.Select(x => Math.Clamp(Math.Round(g + (x - g) * 0.25), 0, 255)).ToArray();
            }
            else
            {
                var c = new[] { 0.6 * sh.R + 0.4 * dp.R, 0.6 * sh.G + 0.4 * dp.G, 0.6 * sh.B + 0.4 * dp.B };
                var m = c.Average();
                if (m < 1) return Array.Empty<double>();
                c = c.Select(x => x / m * 56).ToArray();
                var g = c.Average();
                return c.Select(x => Math.Clamp(Math.Round(g + (x - g) * 0.8), 0, 255)).ToArray();
            }
        }

        static string Base(string? path)
        {
            if (string.IsNullOrEmpty(path)) return "";
            var p = path.Replace('/', '\\').ToLowerInvariant();
            var i = p.LastIndexOf('\\');
            return i >= 0 ? p.Substring(i + 1) : p;
        }

        static string ModelOf(IModeledGetter m)
        {
            try { return Base(m.Model?.File?.ToString()); } catch { return ""; }
        }

        // ------------------------------------------------------------------ main
        public static void RunPatch(IPatcherState<ISkyrimMod, ISkyrimModGetter> state)
        {
            try { RunPatchInner(state); }
            catch (Exception e) { Log("ERROR " + e); throw; }
        }

        static void RunPatchInner(IPatcherState<ISkyrimMod, ISkyrimModGetter> state)
        {
            Log("starting");
            var S = _settings.Value;
            var dataDir = state.DataFolderPath.ToString();
            Log("data folder: " + dataDir);
            var data = LoadData(Path.Combine(dataDir, "ClearSmallWaterfalls", "patcher.json"));
            Log($"patcher data loaded: {data.Drains.Count} drain models");
            var mainKey = ModKey.FromNameAndExtension("ClearSmallWaterfalls.esp");

            bool enb = S.ColourStyle == ColourStyle.ENB;
            if (S.ColourStyle == ColourStyle.Auto)
            {
                var game = Directory.GetParent(dataDir.TrimEnd('\\', '/'))?.FullName ?? "";
                enb = File.Exists(Path.Combine(game, "enbseries.ini")) || File.Exists(Path.Combine(game, "enblocal.ini"));
            }
            Log($"colour style: {(enb ? "ENB" : "vanilla / Community Shaders")}");

            // the final load order WITHOUT the standalone plugin (its edits are recomputed here)
            var listings = state.LoadOrder.PriorityOrder
                .Where(x => x.ModKey != mainKey && x.ModKey != state.PatchMod.ModKey && x.Mod != null)
                .ToList();
            var cache = listings.Select(x => x.Mod!).Reverse().ToList().ToImmutableLinkCache<ISkyrimMod, ISkyrimModGetter>();

            Log($"load order: {listings.Count} plugins (standalone plugin excluded)");
            // models of base objects
            var models = new Dictionary<FormKey, string>();
            var waterActi = new Dictionary<FormKey, FormKey>();
            foreach (var r in listings.MoveableStatic().WinningOverrides()) models[r.FormKey] = ModelOf(r);
            foreach (var r in listings.Static().WinningOverrides()) models[r.FormKey] = ModelOf(r);
            foreach (var r in listings.Door().WinningOverrides()) models[r.FormKey] = ModelOf(r);
            foreach (var r in listings.Activator().WinningOverrides())
            {
                models[r.FormKey] = ModelOf(r);
                if (r.WaterType.FormKeyNullable is FormKey wt && !wt.IsNull) waterActi[r.FormKey] = wt;
            }
            var waters = new Dictionary<FormKey, (System.Drawing.Color Sh, System.Drawing.Color Dp)>();
            foreach (var w in listings.Water().WinningOverrides()) waters[w.FormKey] = (w.ShallowColor, w.DeepColor);

            Log($"base objects: {models.Count}, water activators: {waterActi.Count}, water types: {waters.Count}");
            Kind? KindOf(FormKey b, string m)
            {
                if (data.Drains.ContainsKey(b)) return Kind.Drain;
                if (waterActi.ContainsKey(b)) return Kind.Water;
                if (data.BigFoam.Contains(m)) return Kind.Big;
                if (data.SmallSplash.Contains(m)) return Kind.Small;
                if (data.ImpactMarkers.Contains(m)) return Kind.Marker;
                if (m.Length > 0 && data.BigFalls.Any(p => m.StartsWith(p))) return Kind.Fall;
                return null;
            }

            // collect relevant placed objects from the final load order
            var refs = new Dictionary<FormKey, Ref>();
            var locked = new HashSet<FormKey>();      // touched by our own compatibility patches: leave alone
            var lockedStreams = new List<Ref>();
            foreach (var ctx in listings.PlacedObject().WinningContextOverrides(cache))
            {
                var rec = ctx.Record;
                var b = rec.Base.FormKeyNullable;
                if (b == null || b.Value.IsNull) continue;
                models.TryGetValue(b.Value, out var m);
                var k = KindOf(b.Value, m ?? "");
                if (k == null) continue;
                if ((rec.MajorRecordFlagsRaw & 0x800) != 0) continue;              // initially disabled
                if (rec.Placement == null) continue;
                var isLocked = ctx.ModKey.Name.StartsWith("ClearSmallWaterfalls - ", StringComparison.OrdinalIgnoreCase);
                var r = new Ref
                {
                    Key = rec.FormKey, Kind = k.Value, Model = m ?? "", Base = b.Value, Ctx = ctx,
                    Pos = new double[] { rec.Placement.Position.X, rec.Placement.Position.Y, rec.Placement.Position.Z },
                    Rot = new double[] { rec.Placement.Rotation.X, rec.Placement.Rotation.Y, rec.Placement.Rotation.Z },
                    Scale = rec.Scale ?? 1.0f,
                };
                if (ctx.TryGetParent<ICellGetter>(out var cell)) r.Cell = cell.FormKey;
                if (ctx.TryGetParent<IWorldspaceGetter>(out var ws)) { r.Exterior = true; r.Space = ws.FormKey; }
                else r.Space = r.Cell;
                if (k == Kind.Water) r.WaterType = waterActi[b.Value];
                if (isLocked)
                {   // our own compatibility patches keep their records; their streams only get recoloured below
                    locked.Add(rec.FormKey);
                    lockedStreams.Add(r);
                    continue;
                }
                refs[r.Key] = r;
            }
            // streams the user (or the defaults) want left vanilla: drop them before any analysis, so the stream and its
            // foam stay as they are; the restore step below also undoes what the standalone plugin did to them
            var skyrimKey = ModKey.FromNameAndExtension("Skyrim.esm");
            bool Kept(FormKey k)
            {
                foreach (var raw in S.KeepVanilla)
                {
                    var e = (raw ?? "").Trim();
                    if (e.Length == 0) continue;
                    try
                    {
                        if (e.Contains(':')) { if (ParseKey(e) == k) return true; continue; }
                        var v = uint.Parse(e.StartsWith("0x", StringComparison.OrdinalIgnoreCase) ? e.Substring(2) : e, NumberStyles.HexNumber);
                        if ((v >> 24) == 0) { if (k.ModKey == skyrimKey && k.ID == v) return true; }
                        else if ((v >> 24) == 0xFE) { if (k.ID == (v & 0xFFF)) return true; }
                        else if (k.ID == (v & 0xFFFFFF)) return true;
                    }
                    catch { Log("note: could not read KeepVanilla entry '" + e + "'"); }
                }
                return false;
            }
            var keptVanilla = refs.Values.Where(r => r.Kind == Kind.Drain && Kept(r.Key)).ToList();
            foreach (var k in keptVanilla) refs.Remove(k.Key);
            Log($"kept vanilla: {keptVanilla.Count} streams");
            var bySpace = refs.Values.GroupBy(r => r.Space).ToDictionary(g => g.Key, g => g.ToList());
            Log($"drains found: {refs.Values.Count(r => r.Kind == Kind.Drain)} ({locked.Count} handled by compatibility patches)");

            double[] LandingOf(Ref dr)
            {
                var info = data.Drains[dr.Base];
                var L = new[] { info.LandX, info.LandY, 0.0 };
                if (data.Barrels.TryGetValue(dr.Key, out var bar)) L[1] -= bar.LandingShift;
                var w = Apply(Rot(dr.Rot[0], dr.Rot[1], dr.Rot[2]), new[] { L[0] * dr.Scale, L[1] * dr.Scale, 0 });
                return new[] { dr.Pos[0] + w[0], dr.Pos[1] + w[1], dr.Pos[2] };
            }

            // ---------------- splash / foam / length analysis (same rules as the standalone plugin)
            var disable = new HashSet<FormKey>();
            var toSoft = new Dictionary<FormKey, string>();          // ref -> soft mesh
            var keep = new HashSet<FormKey>();
            var owner = new Dictionary<FormKey, (double D, FormKey Drain, double[] Tgt)>();
            var ripple = new Dictionary<FormKey, (double D, FormKey Drain, double[] Tgt)>();
            var drainLen = new Dictionary<FormKey, double>();
            foreach (var (space, lst) in bySpace)
            {
                var falls = lst.Where(r => r.Kind == Kind.Fall).Select(r => r.Pos).ToList();
                foreach (var dr in lst.Where(r => r.Kind == Kind.Drain))
                {
                    double? Near(Ref r)
                    {
                        var d = H(r.Pos, dr.Pos); var dz = r.Pos[2] - dr.Pos[2];
                        if (d > data.Radius || !(dz > -900 && dz < 40)) return null;
                        if (falls.Count > 0 && falls.Min(fp => H(fp, r.Pos)) < d) return null;
                        return d;
                    }
                    var cands = lst.Where(r => (r.Kind == Kind.Big || r.Kind == Kind.Small || r.Kind == Kind.Marker) && Near(r) != null).ToList();
                    var below = cands.Where(r => r.Pos[2] < dr.Pos[2] - 40).Select(r => r.Pos[2]).ToList();
                    if (below.Count > 0) drainLen[dr.Key] = (dr.Pos[2] - below.Min()) / dr.Scale;
                    var tgt = LandingOf(dr);
                    foreach (var r in cands)
                    {
                        var dd = H(r.Pos, tgt);
                        if (data.WaterRing.Contains(r.Model) && dd < data.MoveMax && (!ripple.ContainsKey(r.Key) || dd < ripple[r.Key].D))
                            ripple[r.Key] = (dd, dr.Key, tgt);
                        if ((r.Kind == Kind.Big || r.Kind == Kind.Small) && dd < data.MoveMax && (!owner.ContainsKey(r.Key) || dd < owner[r.Key].D))
                            owner[r.Key] = (dd, dr.Key, tgt);
                    }
                    var tall = below.Count > 0 && dr.Pos[2] - below.Min() >= data.BigDrop;
                    var big = cands.Where(r => r.Kind == Kind.Big).OrderBy(r => Near(r)!.Value).ToList();
                    var smalls = cands.Where(r => r.Kind == Kind.Small).ToList();
                    if (tall) foreach (var s in smalls) keep.Add(s.Key);
                    else foreach (var s in smalls) if (data.SoftSplash.TryGetValue(s.Model, out var soft)) toSoft[s.Key] = soft;
                    for (int i = 0; i < big.Count; i++)
                    {
                        var f = big[i].Key;
                        if (toSoft.ContainsKey(f) || disable.Contains(f)) continue;
                        if (i == 0 && smalls.Count == 0) toSoft[f] = data.SoftSplash.Values.First(v => v.Contains("long"));   // the long soft splash
                        else disable.Add(f);
                    }
                }
            }
            foreach (var f in keep) { toSoft.Remove(f); disable.Remove(f); }
            var bestRipple = new Dictionary<FormKey, (double D, FormKey Ref)>();
            foreach (var (f, v) in ripple) if (!bestRipple.ContainsKey(v.Drain) || v.D < bestRipple[v.Drain].D) bestRipple[v.Drain] = (v.D, f);
            ripple = bestRipple.Values.ToDictionary(x => x.Ref, x => ripple[x.Ref]);
            foreach (var f in ripple.Keys) { disable.Remove(f); toSoft.Remove(f); }
            var move = owner.Where(kv => !disable.Contains(kv.Key) && !ripple.ContainsKey(kv.Key)).ToDictionary(kv => kv.Key, kv => kv.Value.Tgt);
            if (!S.HandleSplashes) { disable.Clear(); toSoft.Clear(); ripple.Clear(); move.Clear(); }

            // ---------------- water colour per drain
            var tintGroups = new List<double[]>();
            int GroupOf(double[] c)
            {
                for (int i = 0; i < tintGroups.Count; i++)
                {
                    var g = tintGroups[i];
                    if (Math.Sqrt((g[0] - c[0]) * (g[0] - c[0]) + (g[1] - c[1]) * (g[1] - c[1]) + (g[2] - c[2]) * (g[2] - c[2])) < (enb ? 0.5 : data.Merge)) return i;   // ENB table colours are exact: never merge them
                }
                if (tintGroups.Count >= 99)
                {   // merge into the closest existing group
                    return Enumerable.Range(0, tintGroups.Count).OrderBy(i => tintGroups[i].Zip(c, (a, b) => (a - b) * (a - b)).Sum()).First();
                }
                tintGroups.Add(c); return tintGroups.Count - 1;
            }
            var neutral = enb ? data.NeutralEnb : data.NeutralVanilla;
            // ENB: per-area colours (worldspace / weather region / Interior / Default)
            var enbTable = new Dictionary<string, double[]>(StringComparer.OrdinalIgnoreCase);
            if (enb)
            {
                foreach (var line in S.EnbColours ?? new List<string>())
                {
                    try
                    {
                        var kv = line.Split('=');
                        if (kv.Length != 2) continue;
                        var parts = kv[1].Split(new[] { ',', ';', ' ' }, StringSplitOptions.RemoveEmptyEntries)
                                         .Select(x => Math.Clamp(double.Parse(x, CultureInfo.InvariantCulture), 0, 255)).ToArray();
                        if (parts.Length == 3) enbTable[kv[0].Trim()] = parts;
                    }
                    catch { Log("ignored colour line: " + line); }
                }
                if (!enbTable.ContainsKey("Default")) enbTable["Default"] = new double[] { 14, 22, 26 };
                Log("ENB colours: " + string.Join(" | ", enbTable.Select(kv => $"{kv.Key}={kv.Value[0]},{kv.Value[1]},{kv.Value[2]}")));
            }
            // streams placed by our compatibility patches use their own stream models: collect them from those plugins
            foreach (var lst in listings.Where(x => x.ModKey.Name.StartsWith("ClearSmallWaterfalls - ", StringComparison.OrdinalIgnoreCase)))
            {
                try
                {
                    void Scan(ICellGetter c, bool ext)
                    {
                        foreach (var po in c.Persistent.Concat(c.Temporary))
                        {
                            if (po is not IPlacedObjectGetter pl) continue;
                            var bk = pl.Base.FormKeyNullable;
                            if (bk == null || lockedStreams.Any(x => x.Key == pl.FormKey)) continue;
                            if (!cache.TryResolve<IMoveableStaticGetter>(bk.Value, out var bm) || bm.Model == null) continue;
                            if (!bm.Model.File.ToString()!.ToLowerInvariant().Contains("fxwaterfallthin")) continue;
                            lockedStreams.Add(new Ref { Key = pl.FormKey, Kind = Kind.Drain, Base = bk.Value, Cell = c.FormKey, Exterior = ext, Space = c.FormKey });
                        }
                    }
                    foreach (var blk in lst.Mod!.Cells) foreach (var sb in blk.SubBlocks) foreach (var c in sb.Cells) Scan(c, false);
                    foreach (var w in lst.Mod!.Worldspaces)
                    {
                        if (w.TopCell != null) Scan(w.TopCell, true);
                        foreach (var blk in w.SubCells) foreach (var sb in blk.Items) foreach (var c in sb.Items) Scan(c, true);
                    }
                }
                catch (Exception e) { Log($"note: could not read {lst.ModKey}: {e.Message}"); }
            }
            Log($"compatibility-patch streams: {lockedStreams.Count(x => x.Kind == Kind.Drain)}");
            // cell -> worldspace and cell -> regions, read directly from every plugin's worldspace groups (highest priority
            // first), so it does not depend on record-context parents
            var cellWs = new Dictionary<FormKey, FormKey>();
            var cellRegions = new Dictionary<FormKey, List<FormKey>>();
            foreach (var lst in listings)
            {
                try
                {
                    foreach (var w in lst.Mod!.Worldspaces)
                    {
                        void AddCell(ICellGetter? c)
                        {
                            if (c == null) return;
                            cellWs.TryAdd(c.FormKey, w.FormKey);
                            if (!cellRegions.ContainsKey(c.FormKey) && c.Regions != null && c.Regions.Count > 0)
                                cellRegions[c.FormKey] = c.Regions.Select(x => x.FormKey).ToList();
                        }
                        AddCell(w.TopCell);
                        foreach (var blk in w.SubCells)
                            foreach (var sb in blk.Items)
                                foreach (var c in sb.Items) AddCell(c);
                    }
                }
                catch (Exception e) { Log($"note: could not read cells of {lst.ModKey}: {e.Message}"); }
            }
            int fixedExt = 0;
            foreach (var r0 in refs.Values.Concat(lockedStreams))
                if (cellWs.TryGetValue(r0.Cell, out var w0) && !r0.Exterior) { r0.Exterior = true; fixedExt++; }
            Log($"cells mapped: {cellWs.Count}, exterior streams: {refs.Values.Count(r => r.Kind == Kind.Drain && r.Exterior)} (fixed {fixedExt})");
            var regionEdid = new Dictionary<FormKey, string>();
            foreach (var rg in listings.Region().WinningOverrides()) if (rg.EditorID != null) regionEdid[rg.FormKey] = rg.EditorID;
            double[] EnbColourFor(Ref dr)
            {
                if (!dr.Exterior) return enbTable.TryGetValue("Interior", out var ic) ? ic : enbTable["Default"];
                var wsKey = cellWs.TryGetValue(dr.Cell, out var wk) ? wk : dr.Space;
                if (cache.TryResolve<IWorldspaceGetter>(wsKey, out var ws) && ws.EditorID != null && enbTable.TryGetValue(ws.EditorID, out var wc)) return wc;
                if (cellRegions.TryGetValue(dr.Cell, out var regs))
                    foreach (var rk in regs)
                        if (regionEdid.TryGetValue(rk, out var ed) && enbTable.TryGetValue(ed, out var rc)) return rc;
                return enbTable["Default"];
            }
            var groupOf = new Dictionary<FormKey, int>();
            foreach (var dr in refs.Values.Where(r => r.Kind == Kind.Drain))
            {
                double[] col = neutral;
                if (enb) col = EnbColourFor(dr);                   // ENB: per-area colour table
                else if (S.TintStreams)
                {
                    FormKey? wt = null;
                    var placed = bySpace[dr.Space]
                        .Where(r => r.Kind == Kind.Water && r.Pos[2] < dr.Pos[2] + 20 && H(r.Pos, dr.Pos) < data.WaterSearch)
                        .OrderBy(r => H(r.Pos, dr.Pos)).FirstOrDefault();
                    if (placed != null) wt = placed.WaterType;
                    if (wt == null && cache.TryResolve<ICellGetter>(dr.Cell, out var cell) && cell.Water.FormKeyNullable is FormKey cw && !cw.IsNull) wt = cw;
                    if (wt == null && dr.Exterior && cache.TryResolve<IWorldspaceGetter>(dr.Space, out var wsp) && wsp.Water.FormKeyNullable is FormKey ww && !ww.IsNull) wt = ww;
                    if (wt != null && waters.TryGetValue(wt.Value, out var wc))
                    {
                        var t = Tint(wc.Sh, wc.Dp, enb);
                        if (t.Length == 3) col = t;
                    }
                }
                groupOf[dr.Key] = GroupOf(col);
            }
            Log($"tint groups: {tintGroups.Count}");
            for (int i = 0; i < tintGroups.Count; i++)
                Log($"  g{i:00} = {tintGroups[i][0]},{tintGroups[i][1]},{tintGroups[i][2]}  ({groupOf.Count(kv => kv.Value == i)} streams)");

            // ---------------- generated assets (next to the output plugin)
            // Synthesis runs patchers in a temp folder and only keeps the plugin: write generated assets into Data
            // (under MO2 they land in Overwrite). Old generated files are cleared first.
            var outDir = dataDir;
            try
            {
                var genDir = Path.Combine(outDir, "meshes", "clearsmallwaterfalls", "gen");
                if (Directory.Exists(genDir))
                    foreach (var f in Directory.GetFiles(genDir, "*.nif"))
                        if (System.Text.RegularExpressions.Regex.IsMatch(Path.GetFileName(f), @"_g\d\d\.nif$", System.Text.RegularExpressions.RegexOptions.IgnoreCase)) File.Delete(f);
                var texDir = Path.Combine(outDir, "textures", "effects", "clearwater");
                if (Directory.Exists(texDir))   // exactly cwdiff_gNN.dds / cwfront_gNN.dds (Windows wildcards are too loose)
                    foreach (var f in Directory.GetFiles(texDir, "*.dds"))
                        if (System.Text.RegularExpressions.Regex.IsMatch(Path.GetFileName(f), @"^cw(diff|front)_g\d\d\.dds$", System.Text.RegularExpressions.RegexOptions.IgnoreCase)) File.Delete(f);
            }
            catch (Exception e) { Log("note: could not clear old generated files: " + e.Message); }
            var frontSrc = Path.Combine(dataDir, "textures", "effects", "clearwater", "cwfront_p00.dds");
            if (!File.Exists(frontSrc)) throw new FileNotFoundException("Clear Small Waterfalls: missing " + frontSrc + " (install the main mod, version 7.0 or newer).");
            var frontAlpha = Dds.ReadTopAlpha(frontSrc, out var fw, out var fh);
            for (int g = 0; g < tintGroups.Count; g++)
            {
                var c = tintGroups[g];
                byte R = (byte)c[0], G = (byte)c[1], B = (byte)c[2];
                var tdir = Path.Combine(outDir, "textures", "effects", "clearwater");
                Directory.CreateDirectory(tdir);
                Dds.WriteFlat(Path.Combine(tdir, $"cwdiff_g{g:00}.dds"), R, G, B, 4);
                Dds.WriteWithAlpha(Path.Combine(tdir, $"cwfront_g{g:00}.dds"), R, G, B, frontAlpha, fw, fh);
            }
            // streams placed by Clear Small Waterfalls compatibility patches (e.g. GG's Thieves Guild HQ): recolour the
            // textures their own mesh uses with this area's ENB colour (written to the output, which loads after the patch)
            if (enb)
            {
                foreach (var ls in lockedStreams)
                {
                    try
                    {
                        if (!cache.TryResolve<IMoveableStaticGetter>(ls.Base, out var ms) || ms.Model == null) continue;
                        var rel = ms.Model.File.ToString()!.Replace('/', '\\');
                        if (rel.StartsWith("meshes\\", StringComparison.OrdinalIgnoreCase)) rel = rel.Substring(7);
                        var mp = Path.Combine(dataDir, "meshes", rel);
                        if (!File.Exists(mp)) continue;
                        var txt = Encoding.ASCII.GetString(File.ReadAllBytes(mp));
                        var c = EnbColourFor(ls);
                        byte R = (byte)c[0], G = (byte)c[1], B = (byte)c[2];
                        var tdir = Path.Combine(outDir, "textures", "effects", "clearwater");
                        Directory.CreateDirectory(tdir);
                        foreach (System.Text.RegularExpressions.Match m in System.Text.RegularExpressions.Regex.Matches(txt, @"(cw(diff|front)_[A-Za-z0-9]+)\.dds", System.Text.RegularExpressions.RegexOptions.IgnoreCase))
                        {
                            var name = m.Groups[1].Value;
                            if (System.Text.RegularExpressions.Regex.IsMatch(name, @"_(g\d\d|p00|t\d+|d)$", System.Text.RegularExpressions.RegexOptions.IgnoreCase)) continue;
                            var dst = Path.Combine(tdir, name + ".dds");
                            if (m.Groups[2].Value.Equals("diff", StringComparison.OrdinalIgnoreCase)) Dds.WriteFlat(dst, R, G, B, 4);
                            else Dds.WriteWithAlpha(dst, R, G, B, frontAlpha, fw, fh);
                            Log($"recoloured {name}.dds for a compatibility-patch stream ({R},{G},{B})");
                        }
                    }
                    catch (Exception e) { Log("note: could not recolour a compatibility-patch stream: " + e.Message); }
                }
            }
            var meshCache = new Dictionary<(string, int), string>();
            string TintedMesh(string baseRel, int g)
            {
                if (meshCache.TryGetValue((baseRel, g), out var done)) return done;
                var src = Path.Combine(dataDir, "meshes", baseRel);
                if (!File.Exists(src)) throw new FileNotFoundException("Clear Small Waterfalls: missing base mesh " + src);
                var bytes = File.ReadAllBytes(src);
                Replace(bytes, "cwdiff_p00", $"cwdiff_g{g:00}");
                Replace(bytes, "cwfront_p00", $"cwfront_g{g:00}");
                var name = Path.GetFileNameWithoutExtension(baseRel) + $"_g{g:00}.nif";
                var rel = "clearsmallwaterfalls\\gen\\" + name;
                var dst = Path.Combine(outDir, "meshes", "clearsmallwaterfalls", "gen", name);
                Directory.CreateDirectory(Path.GetDirectoryName(dst)!);
                File.WriteAllBytes(dst, bytes);
                meshCache[(baseRel, g)] = rel;
                return rel;
            }

            Log("writing records");
            // ---------------- records
            var msttFor = new Dictionary<string, FormKey>();
            FormKey Mstt(FormKey template, string modelRel, string edid)
            {
                if (msttFor.TryGetValue(modelRel, out var fk)) return fk;
                var src = cache.Resolve<IMoveableStaticGetter>(template);
                var m = state.PatchMod.MoveableStatics.DuplicateInAsNewRecord(src);
                m.EditorID = edid;
                m.Model = new Model { File = modelRel };
                msttFor[modelRel] = m.FormKey;
                return m.FormKey;
            }
            var anyDrainTemplate = data.Drains.Keys.First(k => cache.TryResolve<IMoveableStaticGetter>(k, out _));
            var changed = new HashSet<FormKey>();

            foreach (var dr in refs.Values.Where(r => r.Kind == Kind.Drain))
            {
                var info = data.Drains[dr.Base];
                if (data.Hide.Contains(dr.Key))
                {
                    var o = dr.Ctx.GetOrAddAsOverride(state.PatchMod);
                    o.MajorRecordFlagsRaw |= 0x800;
                    changed.Add(dr.Key); continue;
                }
                int Hb = 0;
                if (S.FitStreamLength && drainLen.TryGetValue(dr.Key, out var Hl) && !(Hl < 60 || Hl + data.Sink + data.Step >= info.DefaultLen))
                {
                    Hb = (int)(Math.Ceiling((Hl + data.Sink) / data.Step) * data.Step);
                    if (!info.Buckets.Contains(Hb)) Hb = info.Buckets.Where(x => x >= Hb).DefaultIfEmpty(0).Min();
                }
                var baseRel = data.Barrels.TryGetValue(dr.Key, out var bar) ? bar.Mesh
                    : "clearsmallwaterfalls\\base\\" + info.Model + (Hb > 0 ? $"_h{Hb}" : "") + ".nif";
                var g = groupOf[dr.Key];
                var rel = TintedMesh(baseRel, g);
                var fk = Mstt(dr.Base, rel, "CSW_" + Path.GetFileNameWithoutExtension(rel));
                var ov = dr.Ctx.GetOrAddAsOverride(state.PatchMod);
                ov.Base.SetTo(fk);
                changed.Add(dr.Key);
            }

            // streams kept vanilla: Clear Small Waterfalls replaces the vanilla stream meshes, so point them at the
            // untouched copies it ships in meshes\clearsmallwaterfalls\vanilla\
            foreach (var dr in keptVanilla)
            {
                var info = data.Drains[dr.Base];
                var rel = "clearsmallwaterfalls\\vanilla\\" + info.Model + ".nif";
                if (!File.Exists(Path.Combine(dataDir, "meshes", rel))) { Log("note: missing " + rel + " (update the main mod)"); continue; }
                var fk = Mstt(dr.Base, rel, "CSW_vanilla_" + info.Model);
                var ov = dr.Ctx.GetOrAddAsOverride(state.PatchMod);
                ov.Base.SetTo(fk);
                changed.Add(dr.Key);
            }

            var vanillaSplashTemplate = new Dictionary<string, FormKey>();
            foreach (var r in listings.MoveableStatic().WinningOverrides())
            {
                var m = ModelOf(r);
                if (data.SoftSplash.ContainsKey(m) && !vanillaSplashTemplate.ContainsKey(m)) vanillaSplashTemplate[m] = r.FormKey;
            }
            foreach (var (f, softMesh) in toSoft)
            {
